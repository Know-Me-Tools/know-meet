/**
 * Renders the Gateway security-header values (wr08 task 8.2) into the one manifest file that
 * carries them: infra/k8s/overlays/production/security-headers.yaml, a local-config ConfigMap
 * that the overlay's replacements copy into every HTTPS rule. This script owns that file
 * completely; nothing else writes it.
 *
 * The Content-Security-Policy is build output (apps/web/dist-hosted-csp.txt, written by
 * `pnpm --filter @know-meet/web run build:hosted`), because it names the public LiveKit URL.
 * The other five values are fixed here.
 *
 *   node tooling/release/src/render-gateway-headers.ts [--repo .] [--csp <file>] [--out <file>]
 *   node tooling/release/src/render-gateway-headers.ts --check [--repo .] [--csp <file>] [--out <file>]
 *
 * Write mode exit 0: the file was written. --check exit 0: the committed file equals the
 * rendering of the artifact. Exit 1 (--check only): the file differs or still holds the
 * placeholder. Exit 2: the input or output could not be read, or the CSP is not a valid
 * header value.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { parseArgs } from "node:util";

const DEFAULT_CSP = "apps/web/dist-hosted-csp.txt";
const DEFAULT_OUT = "infra/k8s/overlays/production/security-headers.yaml";

/**
 * The committed stand-in until the first real render. It fails closed: a sync with it blocks
 * every script, so the site is visibly broken rather than served without its policy.
 */
const PLACEHOLDER_CSP = "default-src 'none'; frame-ancestors 'none'";

/** Gateway API HTTPHeader value: 1 to 4096 characters. */
const MAX_HEADER_VALUE = 4096;
/** Printable ASCII only: no control characters, no line breaks, nothing Envoy would reject. */
const HEADER_VALUE = /^[\x20-\x7e]+$/;

interface Header {
  /** ConfigMap data key; the overlay's replacements read `data.<key>`. */
  readonly key: string;
  readonly value: string;
}

/** In the order the routes list them. */
function headers(csp: string): readonly Header[] {
  return [
    { key: "strict-transport-security", value: "max-age=31536000; includeSubDomains" },
    { key: "content-security-policy", value: csp },
    { key: "x-content-type-options", value: "nosniff" },
    { key: "x-frame-options", value: "DENY" },
    { key: "referrer-policy", value: "strict-origin-when-cross-origin" },
    {
      key: "permissions-policy",
      value: "camera=(self), microphone=(self), geolocation=(), payment=(), usb=()",
    },
  ];
}

class RenderError extends Error {
  readonly line: string;

  constructor(line: string) {
    super("render could not complete");
    this.name = "RenderError";
    this.line = line;
  }
}

/** The whole file, byte for byte. Values are JSON strings, which are valid YAML double-quoted scalars. */
function renderManifest(csp: string): string {
  const status =
    csp === PLACEHOLDER_CSP
      ? "# CSP: PLACEHOLDER. Blocks every script. Run this script on the release artifact before release."
      : "# CSP: generated from the build artifact.";
  const lines = [
    "# GENERATED by tooling/release/src/render-gateway-headers.ts from apps/web/dist-hosted-csp.txt.",
    "# Do not edit by hand. Check: node tooling/release/src/render-gateway-headers.ts --check",
    status,
    "# Read only by kustomize (local-config, not applied): the replacements in kustomization.yaml",
    "# copy each value into the ResponseHeaderModifier of every HTTPS rule in routes.yaml.",
    "apiVersion: v1",
    "kind: ConfigMap",
    "metadata:",
    "  name: know-meet-security-headers",
    "  namespace: know-meet",
    "  annotations:",
    '    config.kubernetes.io/local-config: "true"',
    "data:",
    ...headers(csp).map((header) => `  ${header.key}: ${JSON.stringify(header.value)}`),
  ];
  return `${lines.join("\n")}\n`;
}

/** Reads the artifact exactly as build:hosted writes it (one line, no trailing newline). */
function readCsp(path: string): string {
  let raw: string;
  try {
    raw = readFileSync(path, "utf8");
  } catch {
    throw new RenderError(`ERROR csp-missing ${path} could not be read (run build:hosted first)`);
  }
  if (raw === "" || raw !== raw.trim()) {
    throw new RenderError(`ERROR csp-invalid ${path} is empty or has surrounding whitespace`);
  }
  if (raw.length > MAX_HEADER_VALUE) {
    throw new RenderError(`ERROR csp-too-long ${path} exceeds ${MAX_HEADER_VALUE} characters`);
  }
  if (!HEADER_VALUE.test(raw)) {
    throw new RenderError(`ERROR csp-invalid ${path} holds characters outside printable ASCII`);
  }
  if (raw === PLACEHOLDER_CSP) {
    throw new RenderError(`ERROR csp-placeholder ${path} holds the placeholder policy`);
  }
  return raw;
}

interface Options {
  readonly check: boolean;
  readonly csp: string;
  readonly out: string;
}

function readOptions(argv: readonly string[]): Options {
  try {
    const { values } = parseArgs({
      args: [...argv],
      allowPositionals: false,
      strict: true,
      options: {
        check: { type: "boolean" },
        repo: { type: "string" },
        csp: { type: "string" },
        out: { type: "string" },
      },
    });
    const repo = values.repo ?? ".";
    return {
      check: values.check ?? false,
      csp: resolve(repo, values.csp ?? DEFAULT_CSP),
      out: resolve(repo, values.out ?? DEFAULT_OUT),
    };
  } catch {
    throw new RenderError("ERROR usage expected --check, --repo, --csp and --out only");
  }
}

function check(options: Options, expected: string): number {
  let committed: string;
  try {
    committed = readFileSync(options.out, "utf8");
  } catch {
    throw new RenderError(`ERROR out-missing ${options.out} could not be read`);
  }
  if (committed === renderManifest(PLACEHOLDER_CSP)) {
    process.stdout.write(`FAIL placeholder ${options.out} still holds the placeholder CSP\n`);
    return 1;
  }
  if (committed !== expected) {
    process.stdout.write(`FAIL differs ${options.out} does not match ${options.csp}\n`);
    return 1;
  }
  process.stdout.write(`OK ${options.out} matches ${options.csp}\n`);
  return 0;
}

function main(argv: readonly string[]): number {
  try {
    const options = readOptions(argv);
    const expected = renderManifest(readCsp(options.csp));
    if (options.check) return check(options, expected);
    try {
      writeFileSync(options.out, expected, "utf8");
    } catch {
      throw new RenderError(`ERROR out-unwritable ${options.out} could not be written`);
    }
    process.stdout.write(`WROTE ${options.out}\n`);
    return 0;
  } catch (error) {
    const line =
      error instanceof RenderError
        ? error.line
        : `ERROR render-failed unexpected ${error instanceof Error ? error.name : "unknown"}`;
    process.stderr.write(`${line}\n`);
    return 2;
  }
}

process.exitCode = main(process.argv.slice(2));
