/**
 * HTTP contract of the token service behind same-origin `/api` (WR-1, WR-3, WR-4).
 *
 * wr03 (services/livekit) implements exactly this; wr04's HTTP TokenIssuer
 * adapter calls it. The response envelope mirrors the frozen prototype
 * (docs/design/live/server.mjs): `{ ok: true, data }` or `{ ok: false, error }`.
 * Cross-language types for the app belong in packages/contracts (architect);
 * this file is the test-side statement and the source the specs validate against.
 *
 * Rules every POST endpoint follows:
 * - `Origin` must equal the configured site origin, or 403 `forbidden-origin`.
 * - Body is JSON, `Content-Type: application/json`, at most MAX_BODY_BYTES.
 * - One rate-limit bucket per client address covers both POST endpoints;
 *   behind the Gateway the key is the forwarded client address. Over the
 *   limit: 429 `rate-limited` with a `Retry-After` header in seconds.
 * - Responses carry `Cache-Control: no-store`.
 * GET /api/healthz is not rate limited and needs no Origin.
 */

export const API = {
  createMeeting: "/api/meetings",
  token: "/api/token",
  health: "/api/healthz",
} as const;

/** Room codes, generated by the service only. Same shape as the prototype. */
export const ROOM_CODE_PATTERN = /^km-[a-z0-9]{3}-[a-z0-9]{3}$/;
export const NAME_MAX_LENGTH = 60;
export const MAX_BODY_BYTES = 4096;

export const STATUS = {
  created: 201,
  ok: 200,
  invalidRequest: 400,
  forbiddenOrigin: 403,
  meetingNotFound: 404,
  rateLimited: 429,
} as const;

export type ApiErrorCode =
  | "invalid-request"
  | "forbidden-origin"
  | "meeting-not-found"
  | "rate-limited";

export interface ApiError {
  readonly ok: false;
  readonly error: { readonly code: ApiErrorCode; readonly message: string };
}

/** POST /api/meetings, body `{}` -> 201. */
export interface CreateMeetingResponse {
  readonly ok: true;
  readonly data: { readonly code: string };
}

/** POST /api/token body. Any `code` not issued by the service (any shape) -> 404. */
export interface TokenRequest {
  readonly code: string;
  readonly name: string;
}

/** POST /api/token -> 200. `room` equals the requested code. */
export interface TokenResponse {
  readonly ok: true;
  readonly data: {
    /** Public LiveKit URL, wss://... */
    readonly url: string;
    /** LiveKit access token (JWT). */
    readonly token: string;
    readonly identity: string;
    readonly room: string;
    /** Seconds until the token expires; equals the configured lifetime. */
    readonly expiresIn: number;
  };
}

/** GET /api/healthz -> 200. */
export interface HealthResponse {
  readonly ok: true;
  readonly data: { readonly status: "ok" };
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function dataOf(value: unknown): Record<string, unknown> | null {
  if (!isRecord(value) || value["ok"] !== true) return null;
  const data = value["data"];
  return isRecord(data) ? data : null;
}

export function isCreateMeetingResponse(value: unknown): value is CreateMeetingResponse {
  const data = dataOf(value);
  return data !== null && typeof data["code"] === "string" && ROOM_CODE_PATTERN.test(data["code"]);
}

export function isTokenResponse(value: unknown): value is TokenResponse {
  const data = dataOf(value);
  return (
    data !== null &&
    typeof data["url"] === "string" &&
    data["url"].startsWith("wss://") &&
    typeof data["token"] === "string" &&
    typeof data["identity"] === "string" &&
    typeof data["room"] === "string" &&
    typeof data["expiresIn"] === "number" &&
    data["expiresIn"] > 0
  );
}

export function isHealthResponse(value: unknown): value is HealthResponse {
  const data = dataOf(value);
  return data !== null && data["status"] === "ok";
}

export function isApiError(value: unknown, code: ApiErrorCode): value is ApiError {
  if (!isRecord(value) || value["ok"] !== false) return false;
  const error = value["error"];
  return isRecord(error) && error["code"] === code && typeof error["message"] === "string";
}

/** True when a JSON body carries anything that looks like a token. */
export function carriesToken(value: unknown): boolean {
  return JSON.stringify(value ?? null).includes('"token"');
}
